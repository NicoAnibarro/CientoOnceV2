SET TIME ZONE 'UTC';

CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  email_verificado SMALLINT NOT NULL DEFAULT 0 CHECK (email_verificado IN (0,1)),
  fecha_verificacion_email TIMESTAMPTZ NULL,
  sesion_version INTEGER NOT NULL DEFAULT 0 CHECK (sesion_version >= 0),
  activo SMALLINT NOT NULL DEFAULT 1 CHECK (activo IN (0,1)),
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tokens_autenticacion (
  id_token_autenticacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INTEGER NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
  proposito VARCHAR(30) NOT NULL CHECK (proposito IN ('verificar_email','recuperar_password')),
  token_hash CHAR(64) NOT NULL UNIQUE,
  codigo_hash CHAR(64) NOT NULL,
  vence_en TIMESTAMPTZ NOT NULL,
  usado_en TIMESTAMPTZ NULL,
  intentos SMALLINT NOT NULL DEFAULT 0 CHECK (intentos >= 0),
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_token_usuario_proposito ON tokens_autenticacion(id_usuario,proposito,vence_en);

