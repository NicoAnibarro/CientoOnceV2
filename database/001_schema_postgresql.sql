CREATE OR REPLACE FUNCTION actualizar_fecha_actualizacion()
RETURNS TRIGGER AS $$
BEGIN
  NEW.fecha_actualizacion = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE
  tabla TEXT;
BEGIN
  FOREACH tabla IN ARRAY ARRAY[
    'usuarios','clientes','productos','categorias_productos','insumos','pedidos',
    'compras','movimientos_caja','costos_productos','configuraciones_comerciales',
    'pagos_integracion','tipos_vianda','configuraciones_viandas','pedidos_viandas'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_actualizar_fecha ON %I', tabla);
    EXECUTE format(
      'CREATE TRIGGER trg_actualizar_fecha BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION actualizar_fecha_actualizacion()',
      tabla
    );
  END LOOP;
END;
$$;
